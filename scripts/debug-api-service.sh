#!/usr/bin/env bash
#
# debug-api-service.sh — run the generated ONIX api-service under Delve.
#
# Replaces the normal api-service container with a debug build that:
#   - compiles the Go plugins with -gcflags "all=-N -l"
#   - runs the ONIX server under `dlv exec --headless` on :2345
#
# Requires that scripts/build-api-service.sh has already run, so that
# api-service/build-output/ exists.
#
# Usage:
#   ./scripts/debug-api-service.sh          # build + start the debug container
#   ./scripts/debug-api-service.sh --off    # revert to the normal container
#
# Then in VS Code: Run and Debug -> "Go: attach ONIX api-service (Delve :2345)"
#
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(dirname "$SCRIPT_DIR")"
OVERLAY="$ROOT/docker-compose.api.debug.yml"

info() { echo "  [info]  $*"; }
die()  { echo "  [error] $*" >&2; exit 1; }

[[ -f "$ROOT/docker-compose.api.yml" ]] \
  || die "docker-compose.api.yml not found. Run ./scripts/build-api-service.sh <branch> first."
[[ -d "$ROOT/api-service/build-output/temp" ]] \
  || die "api-service/build-output/ not found. Run ./scripts/build-api-service.sh <branch> first."

# Service name is written into docker-compose.api.yml by the build script.
SERVICE_NAME=$(grep -oE '^  api-[a-z0-9-]+:' "$ROOT/docker-compose.api.yml" | head -1 | tr -d ' :')
[[ -n "$SERVICE_NAME" ]] || die "Could not determine api service name from docker-compose.api.yml"

cd "$ROOT"

if [[ "${1:-}" == "--off" ]]; then
  echo "==> Reverting $SERVICE_NAME to the normal (non-debug) build"
  docker compose -f docker-compose.yml -f docker-compose.api.yml up -d --build "$SERVICE_NAME"
  info "Done. Delve port 2345 is no longer exposed."
  exit 0
fi

echo "==> Writing $OVERLAY  (service: $SERVICE_NAME)"
cat > "$OVERLAY" <<EOF
# Auto-generated by scripts/debug-api-service.sh — safe to delete.
# Overrides the api-service to a Delve-enabled build listening on :2345.

services:
  ${SERVICE_NAME}:
    build:
      context: ./api-service/build-output
      dockerfile: ../../dockerfiles/api-service-debug.Dockerfile
    ports:
      - "2345:2345"
    # Delve needs these to control the process and read its memory.
    security_opt:
      - "seccomp:unconfined"
    cap_add:
      - SYS_PTRACE
EOF

echo "==> Building the debug image (compiles plugins unoptimised — slow first time)"
docker compose \
  -f docker-compose.yml -f docker-compose.api.yml -f "$OVERLAY" \
  up -d --build "$SERVICE_NAME"

echo ""
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo "  Delve listening on  localhost:2345"
echo "  api-service still reachable at  http://localhost:3032"
echo ""
echo "  VS Code: Run and Debug ->"
echo "    \"Go: attach ONIX api-service (Delve :2345)\""
echo ""
echo "  Source for breakpoints:"
echo "    api-service/build-output/temp/automation-beckn-plugins/   (your plugins)"
echo "    api-service/build-output/temp/validationpkg/              (generated validators)"
echo ""
echo "  Revert:  ./scripts/debug-api-service.sh --off"
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
